import { readFile, readdir, lstat, mkdir } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { atomicWrite, fault, projectDirectory, readJson, regularFile, withFileLock, decodeUtf8, utf8Bytes, parseJsonBytes } from '../lib/safe-files.mjs';
import { digest, receiptText } from '../lib/ledger-write.mjs';
import { agentReceiptText } from './agent-receipt.mjs';

const MAX_ROWS = 20;
const safe = (value, limit = 100) => [...String(value).replace(/[\r\n|`<>\[\]\(\)!\\]/g, ' ')].slice(0, limit).join('').trim();

export async function snapshotText(root, project, currentBytes) {
  const dir = await projectDirectory(root, project);
  currentBytes ??= await readFile(join(dir, 'CURRENT_STATE.md'));
  decodeUtf8(currentBytes);
  const currentSha = digest(currentBytes);
  const input = await readJson(join(dir, 'snapshot-input.json'), null);
  if (!input || input.schema !== 1 || !Array.isArray(input.facts) || input.facts.length > 10 ||
      input.facts.some(x => typeof x !== 'string' || x.length > 240) ||
      (input.source_revision !== undefined && !/^(?:[a-f0-9]{40}|[a-f0-9]{64})$/.test(input.source_revision)) ||
      !/^history\/[a-zA-Z0-9_.-]+\.md$/.test(input.history) ||
      !/^[a-f0-9]{64}$/.test(input.history_sha256)) throw fault('CORRUPT', 'invalid snapshot input');
  // Reject linked history parents too; inputs are data, not executable guidance.
  const parent = await lstat(join(dir, 'history'));
  if (!parent.isDirectory() || parent.isSymbolicLink()) throw fault('UNSAFE_PATH', 'linked history');
  await regularFile(join(dir, input.history));
  if (digest(await readFile(join(dir, input.history))) !== input.history_sha256) throw fault('CORRUPT', 'history digest mismatch');
  let names;
  const receiptDir = join(dir, 'receipts');
  try {
    const stat = await lstat(receiptDir);
    if (!stat.isDirectory() || stat.isSymbolicLink()) throw fault('UNSAFE_PATH', 'linked receipts');
    names = await readdir(receiptDir);
  } catch (error) { if (error.code !== 'ENOENT') throw error; names = []; }
  const rows = [];
  for (const name of names.filter(name => name.endsWith('.json')).sort()) {
    const path = join(receiptDir, name);
    await regularFile(path);
    const bytes = await readFile(path);
    const record = parseJsonBytes(bytes);
    const text = record?.kind === 'agent-receipt' ? agentReceiptText(record) : receiptText(record || {});
    if (record.project !== project || name !== `${record.id}.json` || !bytes.equals(utf8Bytes(text))) {
      throw fault('CORRUPT', 'non-canonical or misrouted receipt');
    }
    rows.push({ record, sha256: digest(bytes) });
  }
  // Hash ALL receipts; show only the last 20 by declared time + ID. Declared
  // timestamps sort display, never resolve ownership or establish authority.
  const inputsSha = digest(JSON.stringify({ input, current_sha256: currentSha, receipts: rows.map(x => [x.record.id, x.sha256]) }));
  rows.sort((a, b) => a.record.at.localeCompare(b.record.at) || a.record.id.localeCompare(b.record.id));
  return [
    `# ${project} current snapshot`, '',
    'Generated by fixed rules; ordinary records and reported facts are not execution approval.',
    `Input SHA-256: ${inputsSha}`, `Coordinator source revision: ${input.source_revision || "not-specified"}`, `History: [preserved ledger](../${input.history})`,
    `History SHA-256: ${input.history_sha256}`,
    `Current handoff SHA-256: ${currentSha}`,
    `Unabridged handoff: [preserved input](../history/handoff-${currentSha}.md). Read it for all appended updates; coordinator facts below may lag.`, '',
    '## Current coordination and reported work', '', ...input.facts.map(x => `- ${safe(x, 240)}`), '',
    '## Structured independent receipts', '',
    `Total: ${rows.length}. Showing at most ${MAX_ROWS}; structured sources remain in receipts/. Existing Markdown acknowledgments remain in wakes/.`, '',
    '| ID | Declared actor / source | Reported status |', '| --- | --- | --- |',
    ...rows.slice(-MAX_ROWS).map(({ record: r }) => `| [${r.id}](../receipts/${r.id}.json) | ${safe(r.actor_declared || r.source)} | ${safe(r.status || 'choice recorded')} |`), '',
    'Remote publication: unverified here. Snapshot freshness: run the integrity checker.',
    'Ownership conflicts require a versioned handoff; newest prose or timestamp does not win.', '',
  ].join('\n');
}

async function immutableBytes(path, expected, check) {
  expected = utf8Bytes(expected);
  try {
    await regularFile(path);
    const actual = await readFile(path);
    decodeUtf8(actual);
    if (!actual.equals(expected)) throw fault('CONFLICT', 'immutable snapshot/input differs; original preserved');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    if (check) throw fault('STALE', 'snapshot or preserved input missing for current sources');
    await atomicWrite(path, expected, true);
  }
}

export async function buildSnapshot(root, project, check = false) {
  const dir = await projectDirectory(root, project);
  // Never replace CURRENT_STATE, even when legacy writers ignore our locks.
  // Every byte read is preserved under its own digest before publishing a view.
  const current = await readFile(join(dir, 'CURRENT_STATE.md'));
  const bytes = utf8Bytes(await snapshotText(root, project, current));
  const snapshots = join(dir, 'snapshots');
  if (!check) await mkdir(snapshots, { recursive: true, mode: 0o700 });
  try {
    const stat = await lstat(snapshots);
    if (!stat.isDirectory() || stat.isSymbolicLink()) throw fault('UNSAFE_PATH', 'linked snapshots');
  } catch (error) {
    if (check && error.code === 'ENOENT') throw fault('STALE', 'snapshot missing');
    throw error;
  }
  const filename = `${digest(bytes)}.md`;
  const path = join(snapshots, filename);
  const preserve = async () => {
    await immutableBytes(join(dir, 'history', `handoff-${digest(current)}.md`), current, check);
    await immutableBytes(path, bytes, check);
    // A concurrent append can make the result stale, but cannot be lost.
    if (!current.equals(await readFile(join(dir, 'CURRENT_STATE.md')))) {
      throw fault('STALE', 'handoff changed during generation; all originals preserved; retry');
    }
    return { project, path: `projects/${project}/snapshots/${filename}`, snapshot: 'current', remote: 'not-attempted' };
  };
  return check ? preserve() : withFileLock(join(snapshots, 'generation'), preserve);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [root, project, flag] = process.argv.slice(2);
    if (!root || !project || (flag && flag !== '--check')) throw new Error('Usage: node scripts/build-continuity-snapshot.mjs ROOT PROJECT [--check]');
    console.log(JSON.stringify(await buildSnapshot(root, project, flag === '--check')));
  } catch (error) { console.error(error.code || error.message); process.exitCode = 1; }
}
